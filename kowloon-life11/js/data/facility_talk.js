// ------------------------------------------------------------
// FACILITY_LINES → DialogueDirector 用ノード配列へ展開
// ------------------------------------------------------------
export function buildFacilityNodes() {
  const nodes = [];
  for (const [fac, byChar] of Object.entries(FACILITY_LINES)) {
    for (const [charId, entries] of Object.entries(byChar)) {
      entries.forEach((e, i) => {
        const entry = typeof e === 'string' ? { text: e } : e;
        const baseCond = `location == ${fac}`;
        const cond = entry.cond ? `${baseCond} and (${entry.cond})` : baseCond;
        nodes.push({
          id: `DLG_F_${fac}_${charId}_${i}`,
          owner: charId,
          type: 'TALK',
          pool: 'FAC',
          cond,
          weight: entry.weight ?? 12,
          lines: entry.lines ?? [{ sp: charId, text: entry.text }],
          effects: [...(entry.effects ?? []), 'aff(' + charId + ',1)'],
        });
      });
    }
  }
  return nodes;
}
