// ============================================================
// 一人称プレイヤーの設定値
//
// kowloon-threejs の config/settings.js から、プレイヤー関連だけを抜き出し、
// 狭い九龍城の路地で操作しやすいように調整したもの。
// マジックナンバーはここに集約する。
// ============================================================

export const PLAYER_SETTINGS = {
  // --- 体格 ---
  eyeHeight: 1.6,   // 足元から目線までの高さ (m)
  radius: 0.28,     // 衝突判定の半径 (m) — 幅1.7mの路地でも余裕が片側0.57m

  // --- 移動 ---
  // 実際の人の歩行は 1.2〜1.5 m/s だが、それだと操作していて退屈になる。
  // 「速すぎず、狭さが分かる」ぎりぎりとして 2.2 m/s に置いた。
  walkSpeed: 2.2,
  runSpeed: 3.6,    // 歩行の約1.64倍
  acceleration: 26, // 目標速度への追従の速さ
  damping: 12,      // 入力を離したときの減速

  // --- ジャンプと重力 ---
  // 控えめ。3.0 m/s だと頂点でも約25cmしか上がらない。
  jumpSpeed: 3.0,
  gravity: -18,
  maxFallSpeed: 30, // 落下速度の上限 (床のすり抜け防止)

  // --- 段差 ---
  // これより低い障害物は壁として弾かずに乗り越える。
  // 敷地の段差は18cmなので余裕を持たせてある。
  stepHeight: 0.32,

  // --- 視点 ---
  // 高すぎると狭い路地で酔う。0.0020 は「1画面ぶん振るのに約6cmのマウス移動」。
  mouseSensitivity: 0.002,
  maxPitch: Math.PI / 2 - 0.02,
};

export const WORLD_SETTINGS = {
  // 移動は固定ステップで積分する (フレームレートによる挙動差と貫通を防ぐ)
  fixedTimeStep: 1 / 120,
  maxSubSteps: 5,
  // 万一床の外へ出て落下し続けた場合にスポーンへ戻す高さ
  fallResetY: -20,
};

export const CAMERA_SETTINGS = {
  // 広すぎると壁が歪んで酔う。70度は一人称として自然な範囲。
  fov: 70,
  near: 0.05,
  far: 200,
};
